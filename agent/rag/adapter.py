
"""
agent/rag/adapter.py

RAG integration adapter for WW-P Security AI Agent.

Responsibilities:
- Validate authenticated user context.
- Apply the existing Secure RAG input security pipeline.
- Execute authorization-aware retrieval.
- Convert authorized retrieval results into agent context.
- Extract verified source metadata.
- Prevent unauthorized document content from reaching AgentCore.

Security:
- All document authorization remains inside SecureRetriever.
- Sources are extracted exclusively from RetrievalResult.chunks.
- RetrievalResult.chunks contains ACL-authorized chunks.
- The adapter never accepts source metadata generated by an LLM.

Python 3.10+
"""

from __future__ import annotations

import logging

from dataclasses import dataclass
from typing import Callable

from authentication.auth import UserContext

from retrieval.retriever import (
    SecureRetriever,
    RetrievalResult,
    RetrievalError,
)

from agent.rag.sources import (
    RAGSource,
    SourceExtractor,
    SourceValidationError,
)


logger = logging.getLogger(__name__)


# ============================================================
# EXCEPTIONS
# ============================================================

class RAGAdapterError(Exception):
    """Base exception for agent RAG integration."""


class RAGConfigurationError(RAGAdapterError):
    """Invalid RAG adapter configuration."""


class RAGContextError(RAGAdapterError):
    """Invalid or unavailable RAG context."""


class RAGSecurityError(RAGAdapterError):
    """RAG input security validation failed."""


# ============================================================
# RESULT
# ============================================================

@dataclass(frozen=True, slots=True)
class AgentRAGContext:
    """
    Context returned to AgentCore.

    Only ACL-authorized document content and source metadata
    are exposed.

    Attributes:
        query:
            Sanitized user query.

        context:
            Text generated from authorized retrieved chunks.

        user_id:
            Authenticated user identifier.

        candidates_count:
            Number of vector search candidates.

        authorized_count:
            Number of authorized chunks.

        denied_count:
            Number of denied candidates.

        sources:
            Application-verified source metadata extracted
            from authorized RetrievedChunk objects.
    """

    query: str

    context: str

    user_id: str

    candidates_count: int

    authorized_count: int

    denied_count: int

    sources: tuple[RAGSource, ...] = ()

    @property
    def empty(self) -> bool:
        return self.authorized_count == 0

    @property
    def retrieved_chunks(self) -> int:
        return self.authorized_count


# ============================================================
# RAG ADAPTER
# ============================================================

class RAGAdapter:
    """
    Adapter between AgentCore and SecureRetriever.

    The adapter does not implement its own document authorization.

    All document access decisions remain inside
    SecureRetriever and PermissionManager.

    query_processor must be the existing Secure RAG
    input security pipeline, for example:

        app._apply_prompt_guard

    Source attribution:

        RetrievalResult.chunks
                |
                v
        SourceExtractor
                |
                v
        AgentRAGContext.sources

    Only authorized chunks are accepted as source origins.
    """

    def __init__(
        self,
        retriever: SecureRetriever,
        query_processor: Callable[[str], str],
        default_top_k: int = 5,
    ) -> None:

        if retriever is None:
            raise RAGConfigurationError(
                "SecureRetriever is required."
            )

        if not callable(
            getattr(retriever, "retrieve", None)
        ):
            raise RAGConfigurationError(
                "Retriever must implement retrieve()."
            )

        if not callable(query_processor):
            raise RAGConfigurationError(
                "A valid query security processor is required."
            )

        if (
            not isinstance(default_top_k, int)
            or isinstance(default_top_k, bool)
            or default_top_k <= 0
        ):
            raise RAGConfigurationError(
                "default_top_k must be a positive integer."
            )

        self.retriever = retriever
        self.query_processor = query_processor
        self.default_top_k = default_top_k

    # ========================================================
    # PUBLIC API
    # ========================================================

    def retrieve(
        self,
        query: str,
        user: UserContext,
        *,
        top_k: int | None = None,
    ) -> AgentRAGContext:
        """
        Retrieve authorized context for AgentCore.

        Pipeline:

            Query
              |
              v
            Validation
              |
              v
            Prompt Security
              |
              v
            SecureRetriever
              |
              v
            ACL/RBAC
              |
              v
            Authorized RetrievedChunk objects
              |
              +--------------------+
              |                    |
              v                    v
            Context             Sources
              |                    |
              +--------------------+
                         |
                         v
                  AgentRAGContext

        Raises:
            RAGAdapterError:
                Invalid query or top_k.

            RAGSecurityError:
                Invalid user or rejected query.

            RAGContextError:
                Retrieval or source extraction failure.
        """

        # ----------------------------------------------------
        # STEP 0 - Input validation
        # ----------------------------------------------------

        query = self._validate_query(query)

        self._validate_user(user)

        requested_k = (
            self.default_top_k
            if top_k is None
            else top_k
        )

        if (
            not isinstance(requested_k, int)
            or isinstance(requested_k, bool)
            or requested_k <= 0
        ):
            raise RAGAdapterError(
                "top_k must be a positive integer."
            )

        logger.info(
            "Agent RAG retrieval started: user=%s",
            user.user_id,
        )

        # ----------------------------------------------------
        # STEP 1 - Existing input security pipeline
        # ----------------------------------------------------

        try:

            safe_query = self.query_processor(query)

        except Exception as error:

            logger.warning(
                "Agent RAG input security rejected query: %s",
                type(error).__name__,
            )

            raise RAGSecurityError(
                "Query rejected by the RAG security pipeline."
            ) from error

        if (
            not isinstance(safe_query, str)
            or not safe_query.strip()
        ):
            raise RAGSecurityError(
                "Security pipeline returned an invalid query."
            )

        safe_query = safe_query.strip()

        # ----------------------------------------------------
        # STEP 2 - Secure retrieval
        # ----------------------------------------------------

        try:

            retrieval = self.retriever.retrieve(
                safe_query,
                user,
                top_k=requested_k,
            )

        except RetrievalError as error:

            logger.exception(
                "Agent RAG retrieval failed."
            )

            raise RAGContextError(
                "Secure retrieval failed."
            ) from error

        except Exception as error:

            logger.exception(
                "Unexpected RAG adapter error."
            )

            raise RAGContextError(
                "Unexpected retrieval error."
            ) from error

        # ----------------------------------------------------
        # STEP 3 - Validate retrieval response
        # ----------------------------------------------------

        if not isinstance(retrieval, RetrievalResult):

            raise RAGContextError(
                "Retriever returned an invalid result."
            )

        if retrieval.user_id != user.user_id:

            logger.error(
                "RAG user identity mismatch."
            )

            raise RAGSecurityError(
                "Retrieval result user mismatch."
            )

        # ----------------------------------------------------
        # STEP 4 - Validate retrieval statistics
        # ----------------------------------------------------

        self._validate_retrieval_statistics(
            retrieval
        )

        # ----------------------------------------------------
        # STEP 5 - Build agent context
        # ----------------------------------------------------

        if retrieval.empty:

            context = ""
            sources = ()

        else:

            context = retrieval.context

            if not isinstance(context, str):

                raise RAGContextError(
                    "Retriever returned invalid context."
                )

            if not context.strip():

                raise RAGContextError(
                    "Retriever returned empty context for authorized chunks."
                )

            # ------------------------------------------------
            # STEP 5A - Extract authorized sources
            # ------------------------------------------------

            try:

                sources = SourceExtractor.extract(
                    retrieval.chunks
                )

            except SourceValidationError as error:

                logger.exception(
                    "Source extraction validation failed."
                )

                raise RAGContextError(
                    "Invalid source metadata returned by retriever."
                ) from error

            except Exception as error:

                logger.exception(
                    "Unexpected source extraction error."
                )

                raise RAGContextError(
                    "Unable to extract authorized sources."
                ) from error

            # ------------------------------------------------
            # STEP 5B - Verify source count
            # ------------------------------------------------

            if len(sources) != retrieval.authorized_count:

                logger.error(
                    "Source count mismatch: authorized=%d sources=%d",
                    retrieval.authorized_count,
                    len(sources),
                )

                raise RAGContextError(
                    "Source count does not match authorized chunks."
                )

        # ----------------------------------------------------
        # STEP 6 - Build normalized result
        # ----------------------------------------------------

        result = AgentRAGContext(
            query=safe_query,
            context=context,
            user_id=user.user_id,
            candidates_count=retrieval.candidates_count,
            authorized_count=retrieval.authorized_count,
            denied_count=retrieval.denied_count,
            sources=sources,
        )

        # ----------------------------------------------------
        # STEP 7 - Final consistency validation
        # ----------------------------------------------------

        self._validate_result(result)

        logger.info(
            "Agent RAG retrieval completed: "
            "user=%s candidates=%d authorized=%d denied=%d sources=%d",
            user.user_id,
            result.candidates_count,
            result.authorized_count,
            result.denied_count,
            len(result.sources),
        )

        return result

    # ========================================================
    # QUERY VALIDATION
    # ========================================================

    @staticmethod
    def _validate_query(query: str) -> str:

        if not isinstance(query, str):

            raise RAGAdapterError(
                "Query must be a string."
            )

        query = query.strip()

        if not query:

            raise RAGAdapterError(
                "Query cannot be empty."
            )

        if len(query) > 10_000:

            raise RAGAdapterError(
                "Query is too long."
            )

        return query

    # ========================================================
    # USER VALIDATION
    # ========================================================

    @staticmethod
    def _validate_user(user: UserContext) -> None:

        if not isinstance(user, UserContext):

            raise RAGSecurityError(
                "Authenticated UserContext is required."
            )

        if not user.user_id:

            raise RAGSecurityError(
                "User identity is missing."
            )

        if not user.session_id:

            raise RAGSecurityError(
                "User session is missing."
            )

    # ========================================================
    # RETRIEVAL STATISTICS VALIDATION
    # ========================================================

    @staticmethod
    def _validate_retrieval_statistics(
        retrieval: RetrievalResult,
    ) -> None:
        """
        Validate retrieval statistics and result consistency.
        """

        statistics = (
            retrieval.candidates_count,
            retrieval.authorized_count,
            retrieval.denied_count,
        )

        for value in statistics:

            if (
                not isinstance(value, int)
                or isinstance(value, bool)
                or value < 0
            ):
                raise RAGContextError(
                    "Retrieval statistics must be non-negative integers."
                )

        if retrieval.authorized_count > retrieval.candidates_count:

            raise RAGContextError(
                "Authorized count cannot exceed candidate count."
            )

        if retrieval.denied_count > retrieval.candidates_count:

            raise RAGContextError(
                "Denied count cannot exceed candidate count."
            )

        if (
            retrieval.authorized_count
            + retrieval.denied_count
            > retrieval.candidates_count
        ):
            raise RAGContextError(
                "Retrieval statistics are inconsistent."
            )

        if len(retrieval.chunks) != retrieval.authorized_count:

            raise RAGContextError(
                "Authorized chunk count does not match retrieval statistics."
            )

    # ========================================================
    # RESULT VALIDATION
    # ========================================================

    @staticmethod
    def _validate_result(
        result: AgentRAGContext,
    ) -> None:
        """
        Validate final AgentRAGContext before returning it.
        """

        if not isinstance(result, AgentRAGContext):

            raise RAGContextError(
                "Invalid agent RAG context."
            )

        if result.empty:

            if result.context.strip():

                raise RAGContextError(
                    "Empty RAG context unexpectedly contains data."
                )

            if result.sources:

                raise RAGContextError(
                    "Empty RAG context cannot contain sources."
                )

        else:

            if not result.context.strip():

                raise RAGContextError(
                    "Authorized RAG context is empty."
                )

            if len(result.sources) != result.authorized_count:

                raise RAGContextError(
                    "Source count does not match authorized count."
                )

        for source in result.sources:

            if not isinstance(source, RAGSource):

                raise RAGContextError(
                    "Invalid source object in RAG context."
                )

        citation_ids = [
            source.citation_id
            for source in result.sources
        ]

        expected_ids = list(
            range(1, len(result.sources) + 1)
        )

        if citation_ids != expected_ids:

            raise RAGContextError(
                "Source citation identifiers are inconsistent."
            )
