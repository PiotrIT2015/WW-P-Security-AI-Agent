"""
agent/rag/sources.py

Source attribution components for WW-P Security AI Agent.

Responsibilities:
- Represent authorized RAG sources.
- Extract sources from authorized RetrievedChunk objects.
- Assign deterministic citation identifiers.
- Format source references for assistant responses.

Security:
- Sources must originate from SecureRetriever results.
- Source identifiers are generated by the application.
- No source metadata is accepted from the LLM.

Python 3.10+
"""

from dataclasses import dataclass
from math import isfinite
from typing import Sequence

from retrieval.retriever import RetrievedChunk


# ============================================================
# EXCEPTIONS
# ============================================================

class SourceAttributionError(Exception):
    """Base source attribution exception."""


class SourceValidationError(SourceAttributionError):
    """Invalid source data."""


# ============================================================
# SOURCE MODEL
# ============================================================

@dataclass(frozen=True, slots=True)
class RAGSource:
    """
    Represents one authorized retrieved document chunk.

    citation_id:
        Application-generated source number.

    document_id:
        Original document identifier.

    chunk_id:
        Original retrieved chunk identifier.

    score:
        Vector similarity score.
    """

    citation_id: int

    document_id: str

    chunk_id: str

    score: float

    def __post_init__(self) -> None:

        if (
            not isinstance(self.citation_id, int)
            or isinstance(self.citation_id, bool)
            or self.citation_id <= 0
        ):
            raise SourceValidationError(
                "citation_id must be a positive integer."
            )

        if (
            not isinstance(self.document_id, str)
            or not self.document_id.strip()
        ):
            raise SourceValidationError(
                "document_id must be a non-empty string."
            )

        if (
            not isinstance(self.chunk_id, str)
            or not self.chunk_id.strip()
        ):
            raise SourceValidationError(
                "chunk_id must be a non-empty string."
            )

        if (
            not isinstance(self.score, (int, float))
            or isinstance(self.score, bool)
            or not isfinite(float(self.score))
        ):
            raise SourceValidationError(
                "Source score must be a finite number."
            )

    def to_dict(self) -> dict:
        return {
            "citation_id": self.citation_id,
            "document_id": self.document_id,
            "chunk_id": self.chunk_id,
            "score": float(self.score),
        }


# ============================================================
# SOURCE EXTRACTOR
# ============================================================

class SourceExtractor:
    """
    Extract source metadata from authorized RetrievedChunk objects.

    IMPORTANT:

    This component must receive chunks from RetrievalResult.chunks,
    not raw vector-store candidates.

    SecureRetriever performs ACL/RBAC authorization before returning
    these chunks.
    """

    @staticmethod
    def extract(
        chunks: Sequence[RetrievedChunk],
    ) -> tuple[RAGSource, ...]:

        if not isinstance(chunks, (list, tuple)):
            raise SourceValidationError(
                "Retrieved chunks must be a list or tuple."
            )

        sources = []

        seen = set()

        for index, chunk in enumerate(chunks, start=1):

            if not isinstance(chunk, RetrievedChunk):
                raise SourceValidationError(
                    "Every source must originate from RetrievedChunk."
                )

            document_id = chunk.document_id
            chunk_id = chunk.chunk_id

            if (
                not isinstance(document_id, str)
                or not document_id.strip()
            ):
                raise SourceValidationError(
                    "Retrieved chunk has an invalid document ID."
                )

            if (
                not isinstance(chunk_id, str)
                or not chunk_id.strip()
            ):
                raise SourceValidationError(
                    "Retrieved chunk has an invalid chunk ID."
                )

            source_key = (
                document_id,
                chunk_id,
            )

            if source_key in seen:
                raise SourceValidationError(
                    "Duplicate source detected."
                )

            seen.add(source_key)

            source = RAGSource(
                citation_id=index,
                document_id=document_id,
                chunk_id=chunk_id,
                score=chunk.score,
            )

            sources.append(source)

        return tuple(sources)


# ============================================================
# SOURCE ATTRIBUTOR
# ============================================================

class SourceAttributor:
    """
    Formats application-verified source references.

    The LLM does not control this component.
    """

    @staticmethod
    def format_sources(
        sources: Sequence[RAGSource],
    ) -> str:

        if not isinstance(sources, (list, tuple)):
            raise SourceValidationError(
                "Sources must be a list or tuple."
            )

        if not sources:
            return ""

        lines = [
            "Retrieved sources:"
        ]

        for source in sources:

            if not isinstance(source, RAGSource):
                raise SourceValidationError(
                    "Invalid source object."
                )

            lines.append(
                (
                    f"[{source.citation_id}] "
                    f"Document: {source.document_id} | "
                    f"Chunk: {source.chunk_id}"
                )
            )

        return "\n".join(lines)

    @classmethod
    def append_sources(
        cls,
        answer: str,
        sources: Sequence[RAGSource],
    ) -> str:

        if not isinstance(answer, str) or not answer.strip():
            raise SourceAttributionError(
                "Answer must be a non-empty string."
            )

        formatted_sources = cls.format_sources(sources)

        if not formatted_sources:
            return answer.strip()

        return (
            f"{answer.strip()}\n\n"
            f"{formatted_sources}"
        )