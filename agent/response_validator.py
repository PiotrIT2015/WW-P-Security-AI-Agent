"""
agent/response_validator.py

Response validation component for WW-P Security AI Agent.

Responsibilities:
- Validate generated response content.
- Reject empty or oversized responses.
- Validate RAG citation identifiers.
- Reject citations outside authorized source metadata.
- Prevent model-generated source metadata spoofing.

Security:
- Only application-provided source identifiers are trusted.
- The LLM cannot create authoritative source metadata.
- Citation validation does not guarantee factual correctness.

Python 3.10+
"""

import re
from typing import Iterable

from agent.exceptions import AgentExecutionError


class ResponseValidationError(AgentExecutionError):
    """Raised when an LLM response fails validation."""


class ResponseValidator:
    """
    Validates responses generated by the language model.

    Citation validation is optional.

    If authorized_source_ids is None:
        Citation validation is disabled.

    If authorized_source_ids is an empty collection:
        All numeric citations are rejected.

    If authorized_source_ids contains identifiers:
        Only those identifiers are accepted.
    """

    DEFAULT_MAX_RESPONSE_CHARS = 12000

    # Exact citation format: [1], [2], etc.
    CITATION_PATTERN = re.compile(r"\[(\d+)\]")

    # Detect malformed numeric citation groups, e.g. [ 1 ], [1, 2].
    NUMERIC_BRACKET_PATTERN = re.compile(
        r"\[\s*\d+(?:\s*,\s*\d+)*\s*\]"
    )

    # Reserved application-generated source section.
    RESERVED_SOURCE_HEADER = re.compile(
        r"retrieved\s+sources\s*:",
        re.IGNORECASE,
    )

    def __init__(
        self,
        max_response_chars: int = DEFAULT_MAX_RESPONSE_CHARS,
    ) -> None:

        if (
            not isinstance(max_response_chars, int)
            or isinstance(max_response_chars, bool)
            or max_response_chars <= 0
        ):
            raise ValueError(
                "max_response_chars must be a positive integer."
            )

        self.max_response_chars = max_response_chars

    # ========================================================
    # Main Validation
    # ========================================================

    def validate(
        self,
        response: str,
        authorized_source_ids: Iterable[int] | None = None,
    ) -> str:
        """
        Validate generated response content.

        Args:
            response:
                Text generated by the LLM.

            authorized_source_ids:
                Optional collection of application-authorized
                RAG citation identifiers.

        Returns:
            Normalized response string.

        Raises:
            ResponseValidationError:
                If the response is invalid.
        """

        validated = self._validate_content(response)

        if authorized_source_ids is not None:

            allowed_ids = self._validate_source_ids(
                authorized_source_ids
            )

            self._validate_source_header(validated)

            self._validate_citations(
                validated,
                allowed_ids,
            )

        return validated

    # ========================================================
    # Content Validation
    # ========================================================

    def _validate_content(
        self,
        response: str,
    ) -> str:

        if not isinstance(response, str):
            raise ResponseValidationError(
                "Response must be a string."
            )

        response = response.strip()

        if not response:
            raise ResponseValidationError(
                "Response cannot be empty."
            )

        if len(response) > self.max_response_chars:
            raise ResponseValidationError(
                "Response exceeds the maximum allowed length."
            )

        if "\x00" in response:
            raise ResponseValidationError(
                "Response contains a null character."
            )

        return response

    # ========================================================
    # Source ID Validation
    # ========================================================

    @staticmethod
    def _validate_source_ids(
        source_ids: Iterable[int],
    ) -> frozenset[int]:

        if isinstance(source_ids, (str, bytes, dict)):
            raise ResponseValidationError(
                "Authorized source identifiers must be an iterable "
                "of positive integers."
            )

        try:
            identifiers = list(source_ids)

        except TypeError as exc:
            raise ResponseValidationError(
                "Invalid authorized source identifiers."
            ) from exc

        validated_ids = set()

        for identifier in identifiers:

            if (
                not isinstance(identifier, int)
                or isinstance(identifier, bool)
                or identifier <= 0
            ):
                raise ResponseValidationError(
                    "Authorized source identifiers must be "
                    "positive integers."
                )

            if identifier in validated_ids:
                raise ResponseValidationError(
                    "Duplicate authorized source identifier."
                )

            validated_ids.add(identifier)

        return frozenset(validated_ids)

    # ========================================================
    # Source Header Validation
    # ========================================================

    def _validate_source_header(
        self,
        response: str,
    ) -> None:
        """
        Prevent the model from injecting its own authoritative
        Retrieved sources section.

        The application appends that section independently.
        """

        if self.RESERVED_SOURCE_HEADER.search(response):
            raise ResponseValidationError(
                "Model response contains a reserved source attribution header."
            )

    # ========================================================
    # Citation Validation
    # ========================================================

    def _validate_citations(
        self,
        response: str,
        authorized_ids: frozenset[int],
    ) -> None:
        """
        Validate numeric citations against authorized source IDs.
        """

        numeric_brackets = self.NUMERIC_BRACKET_PATTERN.findall(
            response
        )

        exact_citations = self.CITATION_PATTERN.findall(
            response
        )

        # Every numeric bracket expression must use exact [N] syntax.
        for expression in numeric_brackets:

            if not re.fullmatch(
                r"\[\d+\]",
                expression,
            ):
                raise ResponseValidationError(
                    "Malformed citation format."
                )

        for citation in exact_citations:

            citation_id = int(citation)

            if citation_id not in authorized_ids:
                raise ResponseValidationError(
                    f"Unauthorized citation identifier: [{citation_id}]."
                )